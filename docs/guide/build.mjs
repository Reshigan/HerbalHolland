// Builds docs/Herbal-Holland-System-Guide.pdf from docs/guide/guide.html.
//   node docs/guide/build.mjs            (images: node docs/guide/prepare-images.mjs first, if they changed)
//
// How: Chromium (Playwright) renders the page to a content-only PDF; pypdf reads which page every heading landed on
// (each heading carries a tiny marker); the contents page is filled in and the PDF rendered again; then a second,
// overlay PDF with the running header (chapter name) and the page number for every page is rendered and merged
// onto the content page by page. Cover and chapter openers get no header or footer.
process.env.PLAYWRIGHT_BROWSERS_PATH ??= "/opt/pw-browsers";
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";

const require = createRequire(import.meta.url);
const { chromium } = require("@playwright/test");

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..");
const OUT = join(root, "docs", "Herbal-Holland-System-Guide.pdf");
const WORK = process.env.GUIDE_WORK_DIR || join(tmpdir(), "hh-guide-build");
mkdirSync(WORK, { recursive: true });
const VERSION = "Version 1.5 · 7 October 2026";

// ── Fonts: Outfit (headings) and Inter (text) as data: URLs. The packages ship variable fonts, which Chromium can
// only embed as Type3 outlines (embedded, but nameless); so static instances at the weights the guide uses are made
// once with fontTools into docs/guide/fonts/ and embedded from there. ─────────────────────────────────────────────
const FONT_DIR = join(here, "fonts");
mkdirSync(FONT_DIR, { recursive: true });
const WANTED = [
  ["Outfit", "outfit", "outfit-latin-wght-normal.woff2", "normal", [300, 600, 700]],
  ["Inter", "inter", "inter-latin-wght-normal.woff2", "normal", [400, 500, 600, 700]],
  ["Inter", "inter", "inter-latin-wght-italic.woff2", "italic", [400]],
];
const PY_INSTANCE = `
import sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
src, out, wght = sys.argv[1], sys.argv[2], int(sys.argv[3])
f = TTFont(src)
f.flavor = None
try:
    s = instancer.instantiateVariableFont(f, {"wght": wght}, updateFontNames=True)
except Exception:
    f = TTFont(src); f.flavor = None
    s = instancer.instantiateVariableFont(f, {"wght": wght})
s.save(out)
`;
let css = "/* generated by build.mjs — static instances of the variable fonts in node_modules/@fontsource-variable, embedded as data: URLs */\n";
for (const [family, pkg, file, style, weights] of WANTED) {
  for (const w of weights) {
    const ttf = join(FONT_DIR, `${pkg}-${style}-${w}.ttf`);
    if (!existsSync(ttf)) execFileSync("python3", ["-c", PY_INSTANCE, join(root, "node_modules", "@fontsource-variable", pkg, "files", file), ttf, String(w)], { stdio: "inherit" });
    css += `@font-face { font-family: "${family}"; font-style: ${style}; font-weight: ${w}; font-display: block; src: url(data:font/ttf;base64,${readFileSync(ttf).toString("base64")}) format("truetype"); }\n`;
  }
}
writeFileSync(join(here, "fonts.css"), css);

// ── Python helpers (pypdf; the sandbox's cryptography package is broken, so it is stubbed out) ─────────────────────
const stub = join(WORK, "pystub", "cryptography");
mkdirSync(stub, { recursive: true });
writeFileSync(join(stub, "__init__.py"), 'raise ImportError("stubbed")\n');
const py = (script, ...args) => execFileSync("python3", ["-c", script, ...args], { env: { ...process.env, PYTHONPATH: join(WORK, "pystub") }, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });

const PY_TEXT = `
import sys, json, re
from pypdf import PdfReader
r = PdfReader(sys.argv[1])
pages = []
for p in r.pages:
    t = p.extract_text() or ""
    pages.append(re.sub(r"\\s+", "", t))
print(json.dumps(pages))
`;
const PY_MERGE = `
# Draws the overlay (running header, page number) onto every content page by appending its content stream and
# resources by reference. pypdf's merge_page re-serialises streams and balloons the file; this keeps Chromium's
# compressed streams untouched.
import sys, re
from pypdf import PdfReader, PdfWriter
from pypdf.generic import NameObject, ArrayObject, DictionaryObject, StreamObject, IndirectObject
content, overlay, out = sys.argv[1:4]
c = PdfReader(content); o = PdfReader(overlay)
w = PdfWriter(clone_from=c)
assert len(w.pages) == len(o.pages), (len(w.pages), len(o.pages))
def stream(data):
    s = StreamObject(); s.set_data(data); return w._add_object(s.flate_encode())
q_ref, Q_ref = stream(b"q\\n"), stream(b"Q\\n")
seen = {}
for i, pg in enumerate(w.pages):
    op = o.pages[i]
    oc = op.raw_get("/Contents").get_object() if "/Contents" in op else None
    data = b"".join(x.get_object().get_data() for x in (oc if isinstance(oc, ArrayObject) else [oc])) if oc is not None else b""
    if not data.strip(): continue
    res = pg["/Resources"].get_object()
    ores = op["/Resources"].get_object() if "/Resources" in op else {}
    for cat, entries in ores.items():
        entries = entries.get_object()
        if not isinstance(entries, DictionaryObject): continue
        if cat not in res: res[NameObject(cat)] = DictionaryObject()
        target = res[cat].get_object()
        for key, val in entries.items():
            newkey = "/Ov" + key[1:]
            ident = (cat, key, val.idnum if isinstance(val, IndirectObject) else id(val))
            if ident not in seen:
                cl = val.clone(w)
                seen[ident] = cl if isinstance(cl, IndirectObject) else (cl.indirect_reference if getattr(cl, "indirect_reference", None) is not None else cl)
            target[NameObject(newkey)] = seen[ident]
            data = re.sub(re.escape(key.encode()) + rb"(?![A-Za-z0-9_.])", newkey.encode(), data)
    raw = pg.raw_get("/Contents")
    resolved = raw.get_object()
    parts = list(resolved) if isinstance(resolved, ArrayObject) else [raw]
    assert all(isinstance(x, IndirectObject) for x in parts), "content streams must be indirect"
    pg[NameObject("/Contents")] = ArrayObject([q_ref, *parts, Q_ref, stream(data)])
w.add_metadata({"/Title": "Herbal Holland platform: the complete guide", "/Author": "Herbal Holland", "/Subject": "System guide, ${VERSION.replace(/^Version/, "version")}"})
with open(out, "wb") as f: w.write(f)
`;
const PY_FONTS = `
import sys, json
from pypdf import PdfReader
r = PdfReader(sys.argv[1])
fonts = {}
pages_of = {}
cur = [0]
def walk(fontdict):
    for k, f in fontdict.items():
        f = f.get_object()
        name = str(f.get("/BaseFont"))
        embedded = False
        fd = f.get("/FontDescriptor")
        if fd is None and "/DescendantFonts" in f:
            for d in f["/DescendantFonts"]:
                fd = d.get_object().get("/FontDescriptor")
        if fd is not None:
            fd = fd.get_object()
            embedded = any(key in fd for key in ("/FontFile", "/FontFile2", "/FontFile3"))
        fonts[name] = embedded
        pages_of.setdefault(name, [])
        if cur[0] not in pages_of[name] and len(pages_of[name]) < 6: pages_of[name].append(cur[0])
for n, p in enumerate(r.pages, 1):
    cur[0] = n
    res = p.get("/Resources")
    if res is None: continue
    res = res.get_object()
    if "/Font" in res: walk(res["/Font"].get_object())
    if "/XObject" in res:
        for x in res["/XObject"].get_object().values():
            xo = x.get_object()
            xr = xo.get("/Resources")
            if xr is not None and "/Font" in xr.get_object(): walk(xr.get_object()["/Font"].get_object())
print(json.dumps({"pages": len(r.pages), "fonts": fonts, "pagesOf": pages_of}))
`;

const pageTexts = (pdf) => JSON.parse(py(PY_TEXT, pdf));
const markerPages = (texts) => {
  const map = {};
  texts.forEach((t, i) => {
    for (const m of t.matchAll(/HHMARKx(.+?)xEND/g)) if (!(m[1] in map)) map[m[1]] = i + 1;
  });
  return map;
};

// ── Render ────────────────────────────────────────────────────────────────────────────────────────────────────────
async function launch() {
  try {
    return await chromium.launch();
  } catch (e) {
    for (const p of ["/opt/pw-browsers/chromium", "/opt/pw-browsers/chromium-1194/chrome-linux/chrome"]) {
      if (existsSync(p) && statSync(p).isFile()) return chromium.launch({ executablePath: p });
    }
    throw e;
  }
}

const browser = await launch();
const failed = [];
const consoleErrors = [];
const page = await browser.newPage();
page.on("requestfailed", (r) => failed.push(`${r.url()} — ${r.failure()?.errorText}`));
page.on("console", (m) => m.type() === "error" && consoleErrors.push(m.text()));
await page.goto(pathToFileURL(join(here, "guide.html")).href, { waitUntil: "load" });
await page.evaluate(() => document.fonts.ready);
const images = await page.evaluate(() => [...document.images].map((i) => ({ src: i.getAttribute("src"), ok: i.complete && i.naturalWidth > 0 })));
const broken = images.filter((i) => !i.ok).map((i) => i.src);
const fontsOk = await page.evaluate(() => [document.fonts.check('12px "Outfit"'), document.fonts.check('12px "Inter"')]);

// Number the headings, fill each opener's "In this chapter", build the contents, number the figures, add markers.
const structure = await page.evaluate(() => {
  const toc = document.getElementById("toc-list");
  toc.innerHTML = "";
  document.querySelector("#toc p.muted")?.remove();
  document.querySelector("section.cover").insertAdjacentHTML("beforeend", '<span class="pm">HHMARKxCOVERxEND</span>');
  document.getElementById("toc").insertAdjacentHTML("afterbegin", '<span class="pm">HHMARKxTOCxEND</span>');
  const chapters = [];
  for (const ch of document.querySelectorAll("section.chapter")) {
    const n = ch.dataset.num, title = ch.dataset.title, short = ch.dataset.short;
    ch.querySelector(".opener").insertAdjacentHTML("beforeend", `<span class="pm">HHMARKxOPEN${n}xEND</span>`);
    toc.insertAdjacentHTML("beforeend", `<div class="chap"><span class="n">${n}</span><span class="t">${title}</span><span class="dots"></span><span class="pg" data-key="OPEN${n}">–</span></div>`);
    const list = ch.querySelector(".inthis ul");
    const sections = [];
    const letters = ch.dataset.letters === "1";
    ch.querySelectorAll(".body h2").forEach((h, i) => {
      const num = letters ? String.fromCharCode(65 + i) : `${n}.${i + 1}`;
      const text = h.textContent.trim();
      h.insertAdjacentHTML("afterbegin", `<span class="n">${num}</span>`);
      h.insertAdjacentHTML("beforeend", `<span class="pm">HHMARKxS${n}x${i + 1}xEND</span>`);
      toc.insertAdjacentHTML("beforeend", `<div class="sec"><span class="n">${num}</span><span class="t">${text}</span><span class="dots"></span><span class="pg" data-key="S${n}x${i + 1}">–</span></div>`);
      list.insertAdjacentHTML("beforeend", `<li><b>${num}</b>${text}</li>`);
      sections.push({ key: `S${n}x${i + 1}`, num, text });
    });
    ch.querySelectorAll(".body figure figcaption").forEach((c, i) => c.insertAdjacentHTML("afterbegin", `<span class="fn">Figure ${n}.${i + 1}</span>`));
    chapters.push({ n, title, short, sections, figures: ch.querySelectorAll(".body figure").length });
  }
  return chapters;
});

const pdfOpts = { format: "A4", printBackground: true, preferCSSPageSize: true, margin: { top: "24mm", right: "18mm", bottom: "21mm", left: "18mm" } };
const setToc = (map) => page.evaluate((map) => { for (const el of document.querySelectorAll("#toc-list .pg")) el.textContent = map[el.dataset.key] ?? "–"; }, map);

let map = {};
let texts;
for (let pass = 1; pass <= 4; pass++) {
  const file = join(WORK, `content-pass${pass}.pdf`);
  await page.pdf({ ...pdfOpts, path: file });
  texts = pageTexts(file);
  const next = markerPages(texts);
  const same = JSON.stringify(next) === JSON.stringify(map);
  map = next;
  await setToc(map);
  if (same && pass > 1) break; // the numbers in the contents match where the headings landed
}
const contentPdf = join(WORK, "content.pdf");
await page.pdf({ ...pdfOpts, path: contentPdf });
texts = pageTexts(contentPdf);
const finalMap = markerPages(texts);
if (JSON.stringify(finalMap) !== JSON.stringify(map)) throw new Error("Contents page numbers did not stabilise");
const pageCount = texts.length;

// ── Overlay: running header with the chapter, footer with the page number; none on cover/openers ─────────────────
const openers = structure.map((c) => ({ n: c.n, short: c.short, page: map[`OPEN${c.n}`] })).sort((a, b) => a.page - b.page);
const dark = new Set([map.COVER, ...openers.map((o) => o.page)]);
const chapterOf = (p) => {
  if (p < openers[0].page) return "Contents";
  let cur = openers[0];
  for (const o of openers) if (o.page <= p) cur = o;
  return `${cur.n} · ${cur.short}`;
};
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");
const pagesHtml = Array.from({ length: pageCount }, (_, i) => {
  const p = i + 1;
  if (dark.has(p)) return `<div class="pg"></div>`;
  return `<div class="pg"><div class="hd"><span class="l">Herbal Holland platform guide</span><span class="r">${esc(chapterOf(p))}</span></div><div class="ft"><span class="l">${VERSION}</span><span class="r">${p}</span></div></div>`;
}).join("\n");
const overlayHtml = `<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="fonts.css"><style>
@page { size: A4; margin: 0; }
html, body { margin: 0; padding: 0; }
.pg { width: 210mm; height: 297mm; position: relative; break-after: page; overflow: hidden; font-family: "Inter", sans-serif; color: #57534e; }
.hd, .ft { position: absolute; left: 18mm; right: 18mm; display: flex; justify-content: space-between; align-items: baseline; font-size: 7.6pt; }
.hd { top: 11mm; letter-spacing: 0.12em; text-transform: uppercase; font-weight: 600; border-bottom: 0.25mm solid #d6d3d1; padding-bottom: 1.6mm; }
.hd .r { color: #b8651f; }
.ft { bottom: 10mm; font-size: 8pt; }
.ft .r { font-family: "Outfit", sans-serif; font-weight: 700; font-size: 10.5pt; color: #0c0a09; }
</style></head><body>${pagesHtml}</body></html>`;
const overlayFile = join(here, ".overlay.html");
writeFileSync(overlayFile, overlayHtml);
const overlay = await browser.newPage();
await overlay.goto(pathToFileURL(overlayFile).href, { waitUntil: "load" });
await overlay.evaluate(() => document.fonts.ready);
const overlayPdf = join(WORK, "overlay.pdf");
await overlay.pdf({ format: "A4", printBackground: true, preferCSSPageSize: true, margin: { top: 0, right: 0, bottom: 0, left: 0 }, path: overlayPdf });
await browser.close();
try { execFileSync("rm", ["-f", overlayFile]); } catch {}

py(PY_MERGE, contentPdf, overlayPdf, OUT);

// ── Verify ────────────────────────────────────────────────────────────────────────────────────────────────────────
const info = JSON.parse(py(PY_FONTS, OUT));
const finalTexts = pageTexts(OUT);
const finalMarkers = markerPages(finalTexts);
const tocMismatch = Object.entries(map).filter(([k, v]) => finalMarkers[k] !== v);
const size = statSync(OUT).size;
const ranges = openers.map((o, i) => ({ chapter: `${o.n} ${o.short}`, from: o.page, to: (openers[i + 1]?.page ?? pageCount + 1) - 1 }));
const blank = finalTexts.map((t, i) => ({ p: i + 1, n: t.replace(/HHMARKx.+?xEND/g, "").length })).filter((x) => x.n < 40 && !dark.has(x.p)).map((x) => x.p);
const report = {
  output: OUT,
  blankPages: blank,
  fontPages: info.pagesOf,
  pages: info.pages,
  sizeMB: +(size / 1024 / 1024).toFixed(2),
  fontsEmbedded: info.fonts,
  fontsLoadedInBrowser: { outfit: fontsOk[0], inter: fontsOk[1] },
  images: { total: images.length, broken },
  failedRequests: failed,
  consoleErrors,
  contents: { entries: Object.keys(map).length, mismatches: tocMismatch },
  chapters: ranges,
  coverPage: map.COVER,
  contentsPage: map.TOC,
};
writeFileSync(join(WORK, "report.json"), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
if (broken.length || failed.length || tocMismatch.length || blank.length || size > 15 * 1024 * 1024 || !fontsOk.every(Boolean)) {
  console.error("BUILD CHECKS FAILED");
  process.exit(1);
}
